// ─────────────────────────────────────────────────────────────
// 개인정보/신용정보 입력 탐지 패턴 (입력 차단용)
// 정책: 주민등록번호·신용카드번호·계좌번호·연락처(010)는 어떤 텍스트
//       입력에도 저장할 수 없다. 이메일은 업무상 필요하므로 허용.
// ⚠️ 탐지는 "차단"이 목적이며, 표시용 마스킹(masking.js)과 별개다.
// 오탐(false positive)을 줄이기 위해 경계(\b)와 구분자를 엄격히 둔다.
// ─────────────────────────────────────────────────────────────

// YYYY-MM-DD / YYYY.MM.DD 등 날짜 형태(계좌번호 오탐 방지용)
const DATE_LIKE = /^\d{4}[-\s.]\d{1,2}[-\s.]\d{1,2}$/;

// 검사 순서 중요: 더 구체적인 패턴(주민번호)을 카드/계좌보다 먼저 둔다.
const PII_RULES = [
  {
    type: '주민등록번호',
    // 6자리 생년월일 + (-·공백 선택) + 성별코드(1~4,반드시) + 6자리
    re: /\b(\d{6})[-\s]?([1-4])(\d{6})\b/,
  },
  {
    type: '신용카드번호',
    // 13~16자리, 4자리 그룹을 공백/하이픈으로 구분하거나 연속. 앞자리는 3~6(주요 카드사)
    re: /\b([3-6]\d{3})[-\s]?(\d{4})[-\s]?(\d{4})[-\s]?(\d{1,4})\b/,
  },
  {
    type: '연락처',
    // 휴대폰: 010 으로 시작 + 3~4 + 4 (하이픈/공백 선택). 010 만 차단(정책)
    re: /\b010[-\s]?\d{3,4}[-\s]?\d{4}\b/,
  },
  {
    type: '계좌번호',
    // 은행 계좌: 2~6 - 2~6 - 2~7 형태(구분자 필수). 카드/주민과 겹치지 않도록 뒤 순서.
    re: /\b\d{2,6}[-\s]\d{2,6}[-\s]\d{2,7}\b/,
    // 오탐 방지: 날짜(2026-07-03)는 제외하고, 실제 계좌는 숫자 10자리 이상만 인정
    valid: (m) => !DATE_LIKE.test(m) && (m.replace(/\D/g, '').length >= 10),
  },
];

// 문자열에서 첫 번째로 탐지된 개인정보를 반환. 없으면 null.
// @returns {{ type: string, match: string } | null}
function detectPii(text) {
  if (typeof text !== 'string' || text.length < 6) return null;
  for (const rule of PII_RULES) {
    const m = rule.re.exec(text);
    if (m && (!rule.valid || rule.valid(m[0]))) return { type: rule.type, match: m[0] };
  }
  return null;
}

module.exports = { detectPii, PII_RULES };
