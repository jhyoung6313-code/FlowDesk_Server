/* 날짜(dayjs 또는 'YYYY-MM-DD') → 공휴일명 또는 null
 * custom: DB 등록 공휴일 맵({ 'YYYY-MM-DD': '이름' }). 있으면 내장값보다 우선. */
export function getHoliday(d, custom) {
  const key = typeof d === 'string' ? d.slice(0, 10) : d.format('YYYY-MM-DD');
  if (custom && key in custom) return custom[key];
  return HOLIDAYS[key] || null;
}

export function isHoliday(d, custom) {
  return !!getHoliday(d, custom);
}
